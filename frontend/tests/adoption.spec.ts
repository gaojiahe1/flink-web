import { test, expect } from '@playwright/test'

test('adopt an existing namespace job without mutating Kubernetes', async ({ page, request }) => {
  test.skip(!process.env.E2E_K8S_FIXTURE, 'Requires scripts/mock_kubernetes.py and a fresh test database')
  await page.goto('/')
  await page.getByLabel('用户名').fill(process.env.E2E_USERNAME!)
  await page.getByLabel('密码', { exact: false }).first().fill(process.env.E2E_PASSWORD!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: /Namespace 中发现的既有作业/ })).toBeVisible()
  const row = page.getByRole('row').filter({ hasText: 'existing-e2e-job' })
  await expect(row).toContainText('RUNNING')
  await expect(row).toContainText('existing-e2e-uid')
  page.once('dialog', dialog => dialog.accept())
  await row.getByRole('button', { name: '纳管作业', exact: true }).click()
  await expect(page.getByText(/已纳管 existing-e2e-job，运行配置未修改/)).toBeVisible()
  await expect(page.getByRole('heading', { name: /Namespace 中发现的既有作业/ })).toHaveCount(0)
  const registered = page.getByRole('row').filter({ hasText: 'existing-e2e-job' })
  await expect(registered.getByRole('link', { name: 'Flink UI ↗' })).toHaveAttribute('href', /^\/flink-ui\/[^/]+\/$/)
  await page.screenshot({ path: 'test-results/adopted-job.png', fullPage: true })
  await registered.getByRole('link', { name: '编辑', exact: true }).click()
  await expect(page.getByRole('textbox',{name:'YAML 编辑器',exact:true})).toContainText(/legacy-flink/)
  const yaml = await page.getByRole('textbox',{name:'YAML 编辑器',exact:true}).innerText()
  expect(yaml).toContain('legacy-flink')
  expect(yaml).toMatch(/state.checkpoints.num-retained: ['"]?5/)
  const calls = await (await request.get(process.env.E2E_K8S_FIXTURE! + '/__requests')).json()
  expect(calls.some((call: { path: string }) => call.path.endsWith('/existing-e2e-job'))).toBe(true)
  expect(calls.every((call: { method: string }) => call.method === 'GET')).toBe(true)
})
