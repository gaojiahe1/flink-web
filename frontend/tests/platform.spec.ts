import { test, expect } from '@playwright/test'
test('login, independent manual refresh, catalog and YAML job workflow', async ({ page, context }) => {
  let refreshes = 0
  page.on('request', req => { if(req.url().endsWith('/api/jobs/refresh')) refreshes++ })
  await page.goto('/')
  await page.getByLabel('用户名').fill(process.env.E2E_USERNAME!)
  await page.getByLabel('密码', { exact: false }).first().fill(process.env.E2E_PASSWORD!)
  await page.getByRole('button', { name:'登录', exact:true }).click()
  await expect(page.getByRole('heading', { name:'作业管理', exact:true })).toBeVisible()
  await expect.poll(() => refreshes).toBe(1)
  await expect(page.getByRole('button', { name:/秒后刷新/ })).toBeDisabled()
  await expect(page.getByRole('button', { name:'↻ 刷新状态' })).toBeEnabled({timeout:15000})
  expect(refreshes).toBe(1)
  const other = await context.newPage()
  let otherRefreshes=0
  other.on('request', req => { if(req.url().endsWith('/api/jobs/refresh')) otherRefreshes++ })
  await other.goto('/')
  await expect.poll(() => otherRefreshes).toBe(1)
  expect(refreshes).toBe(1)
  await other.close()
  await page.getByRole('button', { name:'↻ 刷新状态' }).click()
  await expect.poll(() => refreshes).toBe(2)
  await page.getByRole('link', { name:'配置管理' }).click()
  await page.getByRole('button', { name:'＋ 新增' }).click()
  const configId='e2e-'+Date.now()
  await page.getByLabel('唯一标识').fill(configId)
  await page.getByLabel('配置类型').selectOption('secret')
  const secretInput=page.getByLabel('配置值', {exact:false}).first()
  await secretInput.fill('Browser-secret-test')
  await expect(secretInput).toHaveAttribute('type','password')
  const savedSecret = page.waitForRequest(req => req.url().endsWith('/api/catalog/configs/' + configId) && req.method() === 'PUT')
  await page.getByRole('button',{name:'保存',exact:true}).click()
  const secretBody = (await savedSecret).postDataJSON()
  expect(secretBody.value).toMatch(/^fwenc1:/)
  expect(JSON.stringify(secretBody)).not.toContain('Browser-secret-test')
  await expect(page.getByText('已保存',{exact:true})).toBeVisible()
  await expect(page.locator('table')).not.toContainText('Browser-secret-test')
  await page.getByRole('link',{name:'作业模板'}).click()
  await expect(page.getByText('Application 基础模板',{exact:true})).toBeVisible()
  await page.getByRole('link',{name:'作业管理'}).click()
  await page.getByRole('link',{name:'＋ 新建 JAR 作业'}).click()
  await page.getByRole('button',{name:'YAML 编辑',exact:true}).click()
  const name='e2e-job-'+Date.now()
  await page.getByLabel('作业名称').fill(name)
  await page.getByLabel('默认模板').selectOption('application-basic')
  const editor=page.getByRole('textbox',{name:'YAML 编辑器',exact:true})
  const yaml=(await editor.innerText()).replace('name: example-job','name: '+name)
  await editor.fill(yaml)
  await page.getByRole('button',{name:'本地验证与预览'}).click()
  await expect(page.getByText(/本地验证通过；提交时仍需/)).toBeVisible()
  await page.getByRole('button',{name:'保存草稿',exact:true}).click()
  await expect(page.getByRole('button',{name,exact:true})).toBeVisible()
  await page.screenshot({path:'test-results/jobs-page.png',fullPage:true})
})
