test('JDBC Catalog metadata is loaded only by user actions and inserts qualified references',async({page})=>{
 await login(page)
 const suffix=Date.now(), source='source-'+suffix, catalog='jdbc_'+suffix
 await write(page,'/api/catalog/configs/'+source,{name:'测试密码',kind:'secretRef',secretName:'mysql-runtime',secretKey:'password',revision:0})
 await write(page,'/api/catalog/datasources/'+source,{name:'销售库',connectorType:'mysql',tableName:'orders',host:'mysql.test',port:'3306',database:'sales',table:'orders',username:'flink',passwordRef:source,columns:[{name:'id',type:'BIGINT'}],revision:0})
 await write(page,'/api/sql/catalogs/'+catalog,{name:'销售目录',type:'jdbc',dataSourceId:source,defaultDatabase:'sales',revision:0})
 let calls=0
 await page.route('**/api/sql/catalogs/'+catalog+'/metadata',async route=>{
  calls++
  const input=route.request().postDataJSON()
  const data=!input.database?{databases:['sales']}:!input.table?{tables:[{name:'orders',type:'TABLE'}]}:{columns:[{name:'id',type:'BIGINT',primaryKey:true,nullable:false}]}
  await route.fulfill({json:{data:{...data,truncated:false,checkedAt:new Date().toISOString()}}})
 })
 await page.getByRole('link',{name:'SQL 开发',exact:true}).click()
 await page.getByLabel('当前 Catalog',{exact:true}).selectOption(catalog)
 await page.getByRole('button',{name:'Catalog',exact:true}).click()
 expect(calls).toBe(0)
 await page.getByRole('button',{name:'加载数据库',exact:true}).click()
 await page.getByRole('combobox',{name:'数据库',exact:true}).selectOption('sales')
 await page.getByRole('combobox',{name:'数据表',exact:true}).selectOption('orders')
 await expect(page.locator('.metadata-columns')).toContainText('PK')
 await page.getByRole('button',{name:'插入表引用示例',exact:true}).click()
 await expect(page.getByRole('textbox',{name:'SQL 编辑器',exact:true})).toContainText(catalog)
 expect(calls).toBe(3)
 await page.screenshot({path:'test-results/catalog-metadata-browser.png',fullPage:true})
})
